"""Candidate-set index of BP RoboTwin: candidate set id -> LeRobot repo, language, goal.

Source of truth is the RoboTwin side: my_robotwin/bp_tasks/configs/official_tasks.yml (the 40 official tasks and the
suite holding each task's data) and data_bp/<suite>_lerobot/candidate_sets.json (written by the LeRobot export).
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

DEFAULT_ROBOTWIN_ROOT = Path("/vla/workspace/my_robotwin")


def safe_key(candidate_set: str) -> str:
    """'place_shoe_bp/I3/L0/toe_left' -> 'place_shoe_bp__I3__L0__toe_left' (usable as task_type / file name)."""
    return candidate_set.replace("/", "__")


def load_index(robotwin_root: str | Path = DEFAULT_ROBOTWIN_ROOT) -> dict[str, dict]:
    root = Path(robotwin_root)
    official = yaml.safe_load((root / "bp_tasks" / "configs" / "official_tasks.yml").read_text(encoding="utf-8"))["tasks"]
    index: dict[str, dict] = {}
    for suite in sorted({v["suite"] for v in official.values()}):
        lerobot_root = root / "data_bp" / f"{suite}_lerobot"
        entries = json.loads((lerobot_root / "candidate_sets.json").read_text(encoding="utf-8"))
        for cs, e in entries.items():
            task = cs.split("/")[0]
            if official.get(task, {}).get("suite") != suite:
                continue  # task not official, or its formal data lives in another suite
            repo = lerobot_root / e["path"]
            if not (repo / "meta" / "info.json").is_file():
                continue
            index[cs] = {"task": task, "goal": e["goal"], "instruction": e["instruction"], "repo": str(repo),
                         "anchor_id": e["anchor_id"]}
    missing = sorted(set(official) - {v["task"] for v in index.values()})
    if missing:
        raise RuntimeError(f"official tasks without exported candidate sets: {missing}")
    return index


def write_mapping(index: dict[str, dict], path: str | Path) -> Path:
    """BP mapping YAML (format of policy_runtime.bpvav2.load_bp_task_sources) keyed by safe candidate-set keys."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = {"version": 1, "tasks": {safe_key(cs): {"dataset_path": v["repo"]} for cs, v in sorted(index.items())}}
    path.write_text("# generated by server/serve_bprobotwin.py: one entry per BP RoboTwin candidate set\n"
                    + yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    return path
