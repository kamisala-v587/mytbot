#!/bin/bash
# Quick BP RoboTwin closed-loop sweep over several bpv4cdx_b checkpoints, all in parallel (one server + one eval each).
# Same tasks / training scenes for every checkpoint (default: 16 training tasks, 10 episodes each; the 10-episode
# plan contains the earlier 5-episode one, so raising the budget only runs the extra episodes).
# Rerunning an existing <sweep>_<name> only runs the episodes it does not have yet (run_eval resumes per episode uid),
# so adding tasks to an old sweep tops it up without repeating the old tasks.
# usage: source tools/bpv4cdxb/env.local.sh
#        bash tools/bpv4cdxb/sim_sweep_bp.sh <sweep name> name1:<ckpt dir> name2:<ckpt dir> ...
# env:   SWEEP_TASKS (comma list), SWEEP_EPISODES (per task), SWEEP_SCENES (train | bank), SWEEP_PORT0 (first port),
#        SWEEP_TASKS_PER_GPU (parallel tasks per client GPU; each checkpoint uses 2 client GPUs),
#        SWEEP_GROUPS (default "train"; e.g. "heldout_sets, heldout_tasks"), SWEEP_HELDOUT_SETS (episodes per held-out
#        set), SWEEP_HELDOUT_TASKS (episodes per held-out task), SWEEP_TRACE=1 (per-step traces for failure_modes)
# results: /vla/workspace/my_robotwin/eval_result_bp/<sweep>_<name>/ ; summary printed at the end
set -u
SWEEP=${1:?sweep name}
shift
# first 6 = the original diagnosis set (results before 2026-10-31 have only these)
TASKS6=place_shoe_bp,stack_blocks_two_bp,handover_block_bp,stack_bowls_two_bp,click_bell_alarm_bp,place_object_stand_bp
TASKS10=place_a2b_bp,place_object_scale_bp,move_stapler_pad_bp,blocks_ranking_rgb_bp,stack_blocks_three_bp,shake_bottle_bp,place_phone_stand_bp,place_cans_plasticbox_bp,open_laptop_bp,put_object_cabinet_bp
TASKS=${SWEEP_TASKS:-$TASKS6,$TASKS10}
EPS=${SWEEP_EPISODES:-10}
TPG=${SWEEP_TASKS_PER_GPU:-3}
GROUPS_=${SWEEP_GROUPS:-train}
HS=${SWEEP_HELDOUT_SETS:-0}
HT=${SWEEP_HELDOUT_TASKS:-0}
TRACE=$([ "${SWEEP_TRACE:-0}" = 1 ] && echo ", trace: true" || echo "")
SCENES=${SWEEP_SCENES:-train}
PORT=${SWEEP_PORT0:-8031}
RT=/vla/workspace/my_robotwin
RT_PY=/vla/.conda/miniconda3/envs/myrobotwin/bin/python
CFG_DIR=$RT/bp_tasks/configs/eval/sweep
LOGS=$RT/eval_result_bp/_sweep_logs/$SWEEP
mkdir -p "$CFG_DIR" "$LOGS"
cd "$BPV4CDXB_REPO" || exit 1
export LD_LIBRARY_PATH=/vla/workspace/shiliangchao/env/q35va/lib:${LD_LIBRARY_PATH:-}
GPUS=(0 1 2 3)
servers=() evals=() names=()
i=0
for spec in "$@"; do
  name=${spec%%:*}; ckpt=${spec#*:}; port=$((PORT + i)); gpu=${GPUS[$((i % 4))]}
  # clients of eval i start on GPU i+1 so a server and its own clients do not share a GPU first
  cgpus="[$(( (i + 1) % 4 )), $(( (i + 2) % 4 ))]"
  cat > "$CFG_DIR/${SWEEP}_${name}.yml" <<EOF
# generated by tools/bpv4cdxb/sim_sweep_bp.sh ($SWEEP): $ckpt
eval_name: ${SWEEP}_${name}
out_root: eval_result_bp
split: v1
scene_source: $SCENES
tasks: [${TASKS//,/, }]
groups: [$GROUPS_]
budget: {train: $EPS, heldout_sets: $HS, heldout_tasks: $HT}
seed: 0
server: {host: 127.0.0.1, port: $port}
client: {action_horizon: auto$TRACE}
parallel: {gpus: $cgpus, tasks_per_gpu: $TPG}
video: true
EOF
  CUDA_VISIBLE_DEVICES=$gpu nohup python server/serve_bprobotwin.py --ckpt_path "$ckpt" --port $port --infer_horizon 50 \
    --qwen3_5_path "$BPV4CDXB_QWEN_PATH" > "$LOGS/server_$name.log" 2>&1 &
  servers+=($!); names+=("$name")
  echo "$name: server GPU $gpu port $port | clients GPU $cgpus | $ckpt"
  i=$((i + 1))
done
for k in "${!names[@]}"; do
  name=${names[$k]}
  for _ in $(seq 1 90); do
    grep -q "server listening" "$LOGS/server_$name.log" && break
    kill -0 "${servers[$k]}" 2>/dev/null || break  # server process exited: do not wait
    sleep 4
  done
  grep -q "server listening" "$LOGS/server_$name.log" || { echo "server $name failed, see $LOGS/server_$name.log"; tail -5 "$LOGS/server_$name.log"; }
done
for name in "${names[@]}"; do
  (cd "$RT" && $RT_PY -m bp_tasks.eval_policy.run_eval "$CFG_DIR/${SWEEP}_${name}.yml" > "$LOGS/eval_$name.log" 2>&1) &
  evals+=($!)
done
for p in "${evals[@]}"; do wait "$p"; done
kill "${servers[@]}" 2>/dev/null
cd "$RT/eval_result_bp" && for name in "${names[@]}"; do
  $RT_PY - "${SWEEP}_${name}" <<'PY'
import glob, json, sys
e = sys.argv[1]
rows = [json.loads(l) for p in glob.glob(f"{e}/*/episodes.jsonl") for l in open(p) if l.strip()]
by = {}
for r in rows:
    t = by.setdefault(r["task"].replace("_bp", ""), [0, 0]); t[0] += bool(r["success"]); t[1] += 1
print(f"{e}: {sum(r['success'] for r in rows)}/{len(rows)}", {k: f"{a}/{b}" for k, (a, b) in sorted(by.items())})
PY
done
